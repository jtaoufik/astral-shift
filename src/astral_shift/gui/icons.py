def svg(name: str, color: str = "#ffffff", width: float = 1.8) -> bytes:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
        f'stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round">{PATHS[name]}</svg>'
    ).encode()


@lru_cache(maxsize=256)
def image(name: str, size: int, color: str = "#ffffff", width: float = 1.8) -> QImage:
    renderer = QSvgRenderer(QByteArray(svg(name, color, width)))
    img = QImage(size, size, QImage.Format.Format_ARGB32_Premultiplied)
    img.fill(Qt.GlobalColor.transparent)
    p = QPainter(img)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(p, QRectF(0, 0, size, size))
    p.end()
    return img


def icon(name: str, color: str = "#3a2a28") -> QIcon:
    ic = QIcon()
    for s in (16, 24, 32, 48):
        ic.addPixmap(QPixmap.fromImage(image(name, s, color)))
    return ic
